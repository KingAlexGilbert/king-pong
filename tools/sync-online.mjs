import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import vm from 'node:vm';

const root = new URL('../', import.meta.url);
const read = path => readFileSync(new URL(path, root), 'utf8');
function constant(source, name) {
  const start = source.search(new RegExp('\\bconst\\s+' + name + '\\s*='));
  if (start < 0) throw new Error('Missing online contract constant: ' + name);
  return source.slice(start, source.indexOf(';', start) + 1);
}
function write(path, text, check) {
  const url = new URL(path, root);
  if (check) {
    if (!existsSync(url) || read(path) !== text) throw new Error(path + ': run node tools/sync-gameplay.mjs');
  } else if (!existsSync(url) || read(path) !== text) {
    mkdirSync(new URL('.', url), {recursive: true});
    writeFileSync(url, text);
  }
}

export function onlineSources(check) {
  // Read canonical arenas so edits and their compatibility hash sync together.
  const campaigns = vm.runInNewContext(constant(read('game/campaign-data.js'), 'CAMPAIGNS') + '\nCAMPAIGNS', {W: 640, H: 480});
  const rules = vm.runInNewContext(constant(read('game/royal-rules.js'), 'MATCH_RULES') + '\nMATCH_RULES');
  const revision = JSON.parse(read('game/matchmaking-version.json')).revision;
  const fingerprint = createHash('sha256').update(JSON.stringify({campaigns, rules, revision})).digest('hex').slice(0, 16);
  const contract = { protocol: 'royal-' + fingerprint, arenas: campaigns.flatMap((c, i) => c.levels.map((_, j) => i * 6 + j)), rules: 'classic' };
  const literal = JSON.stringify(contract, null, 2);
  const header = '// Generated by tools/sync-gameplay.mjs from the existing arenas/rules and compatibility revision.\n';
  write('signaling/src/matchmaking-contract.js', header + 'export const MATCHMAKING_CONTRACT = Object.freeze(' + literal + ');\n', check);
  const script = header + 'const KING_PONG_MATCHMAKING = Object.freeze(' + literal + ');\n' +
    ['signaling-socket.js', 'network-common.js', 'secure-crypto.js', 'secure-transport.js', 'online.js', 'pairing.js', 'approval-pairing.js', 'matchmaking.js', 'online-wire.js', 'online-engine.js', 'online-match-flow.js', 'multiplayer-rematch.js', 'multiplayer-presence.js', 'online-install.js'].map(f => read('game/' + f)).join('\n');
  write('docs/demo/online.js', script, check);
  write('docs/demo/online-config.js', read('game/online-config.js'), check);
  write('docs/demo/online-localization.js', read('game/online-localization.js'), check);
  return read('game/online-config.js') + read('game/online-localization.js') + script;
}

export function iconSources() {
  const icons = Object.fromEntries([['split', 'royal-split'], ['rush', 'crown-rush'], ['guard', 'castle-guard']]
    .map(([id, name]) => [id, 'data:image/png;base64,' + readFileSync(new URL('game/icons/' + name + '.png', root)).toString('base64')]));
  return 'const ROYAL_APPROVED_ICONS = ' + JSON.stringify(icons, null, 2) + ';\n';
}

export function integrateOnline(source, nativeScript, native) {
  if (native) {
    const begin = '<script id="online-support">', end = '</script>';
    if (source.includes(begin)) {
      const start = source.indexOf(begin), finish = source.indexOf(end, start);
      source = source.slice(0, start) + begin + '\n' + nativeScript + end + source.slice(finish + end.length);
    } else source = source.replace('<script id="royal-localization">', '<script id="online-support">\n' + nativeScript + '</script>\n  <script id="royal-localization">');
  }
  if (!source.includes('\ninstallOnlineSupport();\n')) source = source.replace('\nrecoverInterruptedSaveImport();', '\ninstallOnlineSupport();\nrecoverInterruptedSaveImport();');
  return source;
}
